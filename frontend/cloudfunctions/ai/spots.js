function searchSpotByName(name) {
  if (!name) return []
  const text = String(name).trim()
  const exact = []
  const partial = []
  for (const destId of Object.keys(DEST_SPOTS)) {
    for (const n of DEST_SPOTS[destId]) {
      if (n === text) exact.push({ destId, name: n, id: spotId(destId, n) })
      else if (n.indexOf(text) >= 0 || text.indexOf(n) >= 0) partial.push({ destId, name: n, id: spotId(destId, n) })
    }
  }
  return exact.concat(partial)
}

